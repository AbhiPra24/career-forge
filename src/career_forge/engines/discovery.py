class DiscoveryEngine:
    """Discovers and parses job listings across company tiers."""

    def discover_jobs(self, query: str = "", location: str = "Remote", limit: int = 10) -> List[JobListing]:
        """Discovers at least `limit` relevant job openings across company tiers."""
        listings: List[JobListing] = []
        
        for tier, company_list in TIER_COMPANIES.items():
            for company, title, reqs, loc, salary in company_list:
                listings.append(JobListing(
                    title=title,
                    company=company,
                    location=loc,
                    tier=tier,
                    requirements=reqs,
                    salary_range=salary,
                    description=f"{company} is hiring a {title}. Core tech stack: {', '.join(reqs)}."
                ))

        # Filter or sort by query if provided
        if query:
            q_lower = query.lower()
            listings.sort(
                key=lambda j: (
                    any(term in j.title.lower() for term in q_lower.split()) or
                    any(term in " ".join(j.requirements).lower() for term in q_lower.split())
                ),
                reverse=True
            )

        return listings[:max(limit, 10)]

    def generate_strategy_report(self, digest: ProfileDigest, jobs: List[JobListing], matcher: TalentScoutEngine) -> str:
        """Generates comprehensive strategy markdown report."""
        year = datetime.datetime.now().year
        evaluations = [(job, matcher.evaluate_fit(digest, job)) for job in jobs]
        evaluations.sort(key=lambda x: x[1].fit_score, reverse=True)

        md_lines = [
            f"# {digest.candidate_name.upper()} – JOB RESEARCH STRATEGY REPORT ({year})",
            "",
            "> **Generated by CareerForge (`career-forge`)** | Production-Grade Career Intelligence",
            "",
            "---",
            "",
            "## 1. Executive Profile Audit & Differentiators",
            f"- **Target Career Stage:** `{digest.career_stage}`",
            f"- **Primary Domain Expertise:** {', '.join(digest.domain_expertise)}",
            f"- **Core Tech Stack:** `{', '.join(digest.core_stack)}`",
            f"- **Inferred Target Roles:** {', '.join(digest.target_roles)}",
            "",
            "### Quantified High-Impact Accomplishments",
        ]

        for metric in digest.top_metrics:
            md_lines.append(f"- ✅ **{metric}**")

        md_lines.extend([
            "",
            "---",
            "",
            "## 2. Top Open Requisitions & 4-Factor Fit Analysis",
            "",
            "| Company | Role Title | Tier | Location | Fit Score | Action Batch | Key Matched Skills |",
            "| :--- | :--- | :--- | :--- | :---: | :--- | :--- |"
        ])

        for job, ev in evaluations:
            skills_str = ", ".join(ev.matched_skills[:3]) if ev.matched_skills else "General Align"
            md_lines.append(
                f"| **{job.company}** | {job.title} | {job.tier.split('(')[0].strip()} | {job.location} | **{ev.fit_score}%** | `{ev.action_batch.split('(')[1].rstrip(')')}` | `{skills_str}` |"
            )

        md_lines.extend([
            "",
            "---",
            "",
            "## 3. Targeted 3-Layer Outreach Playbook",
            "",
            "### Layer 1: Direct Engineering Leader Pitch",
            "```text",
            f"Subject: {digest.target_roles[0] if digest.target_roles else 'Senior Engineer'} – Distributed Systems & High-Throughput Pipelines",
            "",
            "Hi [Hiring Manager],",
            "",
            f"I came across your team's work scaling systems at [Company]. Over the past {digest.years_of_experience or 5}+ years, I have focused on {', '.join(digest.domain_expertise[:2])}.",
            f"Most recently: {digest.top_metrics[0] if digest.top_metrics else 'Architected high-throughput distributed microservices'}.",
            "",
            "I would love to connect and share how my background in Go, Kafka, and Kubernetes could help support your roadmap.",
            "",
            f"Best regards,",
            f"{digest.candidate_name}",
            "```",
            "",
            "---",
            f"*Report compiled on {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')} via CareerForge.*"
        ])

        return "\n".join(md_lines)
